class StrictSettingsModel(BaseModel):
    model_config = ConfigDict(extra="forbid")


class BasicSettings(StrictSettingsModel):
    institutionName: str = Field(min_length=1, max_length=80)
    collegeCode: str = Field(max_length=20)
    affiliation: str = Field(max_length=120)
    principalName: str = Field(max_length=80)
    address: str = Field(max_length=300)
    officialEmail: str = Field(max_length=120)
    website: str = Field(max_length=160)
    academicYear: str = Field(pattern=r"^\d{4}-\d{4}$")
    language: Literal["English"]
    timeFormat: Literal["12-hour", "24-hour"]
    theme: Literal["light", "dark", "system"]

    @field_validator("institutionName")
    @classmethod
    def institution_name_must_not_be_blank(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("institution name must not be blank")
        return value

    @field_validator("officialEmail")
    @classmethod
    def validate_official_email(cls, value: str) -> str:
        value = value.strip()
        if value and ("@" not in value or "." not in value.rsplit("@", 1)[-1]):
            raise ValueError("enter a valid official email address")
        return value

    @field_validator("website")
    @classmethod
    def validate_website(cls, value: str) -> str:
        value = value.strip()
        if value and not value.startswith(("https://", "http://")):
            raise ValueError("website must start with http:// or https://")
        return value


class TimetableSettings(StrictSettingsModel):
    workingDays: list[int] = Field(min_length=1, max_length=6)
    periodsPerDay: int = Field(ge=1, le=12)
    dayStart: str = Field(pattern=r"^(?:[01]\d|2[0-3]):[0-5]\d$")
    periodMinutes: Literal[45, 50, 60]
    lunchAfterPeriod: int = Field(ge=1, le=12)
    intervalAfterPeriod: int = Field(ge=0, le=12)
    intervalMinutes: int = Field(ge=0, le=60)
    lunchMinutes: int = Field(ge=0, le=120)
    weeklyPeriodTarget: int = Field(ge=1, le=60)
    pdfTitle: str = Field(min_length=1, max_length=80)
    includeInstitutionName: bool
    pdfTemplate: Literal["modern", "classic", "minimal"]
    timetablePdfTemplate: Literal["modern", "classic", "minimal"]
    masterPdfTemplate: Literal["modern", "classic", "minimal"]
    pdfStructure: dict | None = None
    pdfAccent: str = Field(pattern=r"^#[0-9a-fA-F]{6}$")
    pdfFooter: str = Field(max_length=100)
    pdfBackgroundImage: str = Field(max_length=2_100_000)
    pdfBackgroundOpacity: float = Field(ge=0.05, le=1.0)
    pdfContentPosition: Literal["top", "middle", "bottom"]

    @model_validator(mode="before")
    @classmethod
    def discard_removed_legacy_fields(cls, value):
        if not isinstance(value, dict):
            return value
        cleaned = dict(value)
        for key in (
            "maxConsecutivePeriods", "facultyDailyLimit", "labBlockPeriods",
            "conflictHandling", "notifyFaculty", "notifyStudents", "requireApproval",
        ):
            cleaned.pop(key, None)
        return cleaned

    @field_validator("workingDays")
    @classmethod
    def validate_working_days(cls, value: list[int]) -> list[int]:
        if any(day < 1 or day > 6 for day in value):
            raise ValueError("working days must be between 1 and 6")
        if len(value) != len(set(value)):
            raise ValueError("working days must be unique")
        return sorted(value)

    @field_validator("pdfBackgroundImage")
    @classmethod
    def validate_background_image(cls, value: str) -> str:
        allowed = ("data:image/png;base64,", "data:image/jpeg;base64,")
        if value and not value.startswith(allowed):
            raise ValueError("background must be an embedded PNG or JPEG image")
        return value

    @model_validator(mode="after")
    def validate_lunch_period(self):
        if self.lunchAfterPeriod > self.periodsPerDay:
            raise ValueError("lunch period cannot exceed periods per day")
        return self


@router.post("/template-structure")
async def import_template_structure(file: UploadFile = File(...), _user=Depends(require_hod_or_above())):
    if not file.filename or not file.filename.lower().endswith(".docx"):
        raise HTTPException(status_code=400, detail="Upload a .docx timetable structure file")
    content = await file.read()
    if len(content) > 5_000_000:
        raise HTTPException(status_code=413, detail="Template file must be smaller than 5 MB")
    try:
        with zipfile.ZipFile(io.BytesIO(content)) as archive:
            document = ET.fromstring(archive.read("word/document.xml"))
        ns = {"w": "http://schemas.openxmlformats.org/wordprocessingml/2006/main"}
        tables = document.findall(".//w:tbl", ns)
        parsed_tables = []
        for table in tables:
            parsed_tables.append([["".join(node.text or "" for node in cell.findall(".//w:t", ns)).strip() for cell in row.findall("./w:tc", ns)] for row in table.findall("./w:tr", ns)])
        grid = None
        grid_index = -1
        for index, rows in enumerate(parsed_tables):
            if rows and any("DAY" in cell.upper() and "PERIOD" in cell.upper() for cell in rows[0]):
                grid = rows
                grid_index = index
                break
        if not grid:
            raise ValueError("Could not find a timetable grid headed DAY / PERIOD")
        header = grid[0]
        period_columns = []
        for column, label in enumerate(header[1:], start=1):
            name = label.strip().upper()
            if name in {"BREAK", "INTERVAL"}:
                period_columns.append({"kind": "break", "label": "BREAK"})
            elif name in {"LUNCH", "LUNCH BREAK"}:
                period_columns.append({"kind": "lunch", "label": "LUNCH"})
            else:
                period_columns.append({"kind": "period", "label": name or f"P{column}"})
        subject_table = parsed_tables[grid_index + 1] if grid_index + 1 < len(parsed_tables) else []
        coordinator_table = parsed_tables[grid_index + 2] if grid_index + 2 < len(parsed_tables) else []
        approval_table = parsed_tables[grid_index + 3] if grid_index + 3 < len(parsed_tables) else []
        subject_groups = [row[0].strip().upper() for row in subject_table if row and row[0].strip().upper() in {"THEORY", "PRACTICALS", "PRACTICAL", "LAB"}]
        coordinator_labels = [cell.strip().rstrip(":") for row in coordinator_table for cell in row if cell.strip()] if coordinator_table else ["CLASS COORDINATOR", "FACULTY ADVISOR"]
        approval_labels = [cell.strip() for row in approval_table[-1:] for cell in row if cell.strip()] if approval_table else ["DEPT. TT COORDINATOR", "OVERALL TT COORDINATOR", "HOD", "VICE-PRINCIPAL", "PRINCIPAL"]
        return {
            "columns": period_columns,
            "workingDays": [row[0] for row in grid[2:] if row and row[0].strip()],
            "subjectHeaders": subject_table[0] if subject_table else ["S.NO", "SUB-CODE", "SUBJECT", "CREDIT", "FACULTY NAME", "DESIGNATION & DEPT.", "NO. HRS/WEEK"],
            "subjectGroups": subject_groups or ["THEORY", "PRACTICALS"],
            "coordinatorLabels": coordinator_labels,
            "approvalLabels": approval_labels,
            "sourceName": file.filename,
        }
    except HTTPException:
        raise
    except Exception as error:
        raise HTTPException(status_code=400, detail=f"Could not read timetable structure: {error}") from error


class SettingsPayload(StrictSettingsModel):
    defaultSemesterCycle: Literal["odd", "even"]
    basic: BasicSettings
    timetable: TimetableSettings

@router.get("")
async def get_settings(db: AsyncSession = Depends(get_db), _user=Depends(get_current_user)):
    record = await db.get(WorkspaceSettings, "default")
    if not record:
        return DEFAULTS
    saved = json.loads(record.settings_json or "{}")
    saved_basic = saved.get("basic", {})
    saved_timetable = saved.get("timetable", {})
    if saved_timetable.get("pdfFooter") == "Generated by SmartSchedule":
        saved_timetable["pdfFooter"] = "Generated by SEC SchedX"
    return {
        **DEFAULTS,
        "defaultSemesterCycle": saved.get("defaultSemesterCycle", DEFAULTS["defaultSemesterCycle"]),
        "basic": {key: saved_basic.get(key, value) for key, value in DEFAULTS["basic"].items()},
        "timetable": {key: saved_timetable.get(key, value) for key, value in DEFAULTS["timetable"].items()},
    }

@router.put("")
async def save_settings(payload: SettingsPayload, db: AsyncSession = Depends(get_db), user=Depends(require_hod_or_above())):
    data = payload.model_dump()
    record = await db.get(WorkspaceSettings, "default")
    if record:
        record.settings_json = json.dumps(data)
        record.updated_by = user.id
    else:
        db.add(WorkspaceSettings(id="default", settings_json=json.dumps(data), updated_by=user.id))
    await db.commit()
    return data
